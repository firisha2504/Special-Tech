import fs from 'fs';
import path from 'path';

/**
 * Generate a professional Special Tech Project Specification PDF document stream
 */
export const generateSpecificationPDF = (requirement, customer, inquiry) => {
  const doc = new PDFDocument({ margin: 45, size: 'A4' });

  // Special Tech Brand Colors from Official Logo
  const primaryNavy = '#020D20';
  const electricBlue = '#087BFF';
  const cyan = '#08D9E8';
  const slateText = '#475569';
  const darkText = '#020D20';

  // 1. Header Banner
  doc.rect(0, 0, doc.page.width, 100).fill(primaryNavy);

  const logoPath = path.resolve('src/assets/logo/special-tech-horizontal.png');
  if (fs.existsSync(logoPath)) {
    doc.image(logoPath, 45, 24, { height: 50 });
  } else {
    doc
      .fillColor('#FFFFFF')
      .fontSize(22)
      .font('Helvetica-Bold')
      .text('SPECIAL TECH', 45, 30);

    doc
      .fillColor(cyan)
      .fontSize(9)
      .font('Helvetica')
      .text('INNOVATION • INTELLIGENCE • SOLUTIONS', 45, 56);
  }

  doc
    .fillColor('#A7B8D0')
    .fontSize(9)
    .text(`Inquiry ID: ${inquiry?.inquiryNumber || 'ST-SPEC-2026'}`, doc.page.width - 200, 32, { align: 'right', width: 155 })
    .text(`Date: ${new Date().toLocaleDateString()}`, doc.page.width - 200, 48, { align: 'right', width: 155 });

  doc.moveDown(4);

  // 2. Document Title
  doc
    .fillColor(darkText)
    .fontSize(18)
    .font('Helvetica-Bold')
    .text('AI-Generated Software Specification & Proposal', 45, 120);

  doc
    .fillColor(slateText)
    .fontSize(10)
    .font('Helvetica')
    .text(`Prepared for: ${customer?.name || 'Valued Client'} ${customer?.company ? `(${customer.company})` : ''} | Email: ${customer?.email || 'N/A'}`);

  doc.moveDown(1);
  doc.strokeColor('#E2E8F0').lineWidth(1).moveTo(45, doc.y).lineTo(doc.page.width - 45, doc.y).stroke();
  doc.moveDown(1.5);

  // 3. Project Overview
  doc.fillColor(electricBlue).fontSize(13).font('Helvetica-Bold').text('1. PROJECT OVERVIEW');
  doc.moveDown(0.4);
  doc.fillColor(darkText).fontSize(10).font('Helvetica').text(requirement.overview || 'Comprehensive custom software platform.');
  doc.moveDown(1.2);

  // 4. Problem Statement & Objectives
  doc.fillColor(electricBlue).fontSize(13).font('Helvetica-Bold').text('2. PROBLEM STATEMENT & OBJECTIVES');
  doc.moveDown(0.4);
  doc.fillColor(darkText).fontSize(10).font('Helvetica').text(`Core Challenge: ${requirement.problemStatement || 'Operational bottlenecks.'}`);
  doc.moveDown(0.5);

  if (Array.isArray(requirement.objectives)) {
    doc.fillColor(darkText).fontSize(10).font('Helvetica-Bold').text('Key Objectives:');
    requirement.objectives.forEach((obj, idx) => {
      doc.fillColor(slateText).fontSize(9.5).font('Helvetica').text(`  • ${obj}`);
    });
  }
  doc.moveDown(1.2);

  // 5. System Modules
  doc.fillColor(electricBlue).fontSize(13).font('Helvetica-Bold').text('3. CORE SYSTEM MODULES');
  doc.moveDown(0.4);

  if (Array.isArray(requirement.modules)) {
    requirement.modules.forEach((mod) => {
      doc.fillColor(darkText).fontSize(10).font('Helvetica-Bold').text(`• ${mod.name}: `, { continued: true });
      doc.fillColor(slateText).fontSize(9.5).font('Helvetica').text(mod.desc || mod.description || '');
    });
  }
  doc.moveDown(1.2);

  // 6. Recommended Technology Stack
  doc.fillColor(electricBlue).fontSize(13).font('Helvetica-Bold').text('4. RECOMMENDED ARCHITECTURAL STACK');
  doc.moveDown(0.4);

  if (Array.isArray(requirement.recommendedTech)) {
    requirement.recommendedTech.forEach((tech) => {
      doc.fillColor(darkText).fontSize(10).font('Helvetica-Bold').text(`• ${tech.layer}: `, { continued: true });
      doc.fillColor(slateText).fontSize(9.5).font('Helvetica').text(tech.technology || '');
    });
  }
  doc.moveDown(1.2);

  // 7. Deliverables & Next Steps
  doc.fillColor(electricBlue).fontSize(13).font('Helvetica-Bold').text('5. EXPECTED DELIVERABLES & NEXT STEPS');
  doc.moveDown(0.4);

  if (Array.isArray(requirement.deliverables)) {
    requirement.deliverables.forEach((del) => {
      doc.fillColor(slateText).fontSize(9.5).font('Helvetica').text(`  ✓ ${del}`);
    });
  }

  // Footer Note
  doc.moveDown(2);
  doc.strokeColor('#E2E8F0').lineWidth(1).moveTo(45, doc.y).lineTo(doc.page.width - 45, doc.y).stroke();
  doc.moveDown(1);

  doc
    .fillColor(slateText)
    .fontSize(8.5)
    .font('Helvetica-Oblique')
    .text(
      'Special Tech (https://specialtech.com) — Confidential Client Specification. Generated by Special Tech AI Engine.',
      { align: 'center' }
    );

  doc.end();
  return doc;
};
